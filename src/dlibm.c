/*
** The wrappers.
**
** Each is 'lmathlib.c''s function with the platform call swapped for the
** vendored one, and nothing else: the same argument checking, the same
** number of results, the same behaviour on a bad argument. A program
** cannot tell which build it is running on except by the last bit of an
** answer, which is the point.
*/

static int dvlibm_exp (lua_State *L) {
  lua_pushnumber(L, dv_exp(luaL_checknumber(L, 1)));
  return 1;
}

/*
** 'math.log' takes an optional base, and lmathlib.c special-cases 2 and
** 10 so that log(8, 2) is exactly 3 rather than log(8)/log(2). Both
** special cases are kept -- dropping them would change an answer a
** program already relies on, on every target at once.
*/
static int dvlibm_log (lua_State *L) {
  lua_Number x = luaL_checknumber(L, 1);
  lua_Number res;
  if (lua_isnoneornil(L, 2))
    res = dv_log(x);
  else {
    lua_Number base = luaL_checknumber(L, 2);
    if (base == 2.0)
      res = dv_log2(x);
    else if (base == 10.0)
      res = dv_log10(x);
    else
      res = dv_log(x) / dv_log(base);
  }
  lua_pushnumber(L, res);
  return 1;
}

