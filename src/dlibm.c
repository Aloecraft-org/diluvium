/*
** dlibm.c
** The embedded libm, and the 'math' entries that route through it.
**
** See dlibm.h for why an embedded libm exists at all. This file is two
** things: the translation unit the vendored openlibm sources are
** compiled in, and the wrappers that put them behind 'math.exp' and its
** neighbours.
**
** Vendored, not written. src/libm/ holds openlibm's sources changed only
** by script/vendor_libm.sh -- four includes replaced, every exported
** symbol prefixed 'dv_', two export decorations dropped. src/libm/
** PROVENANCE names the upstream commit and LICENSE.md is upstream's,
** verbatim. No constant, branch or algorithm is altered, and the reason
** to keep it that way is the whole point of vendoring: what makes these
** functions trustworthy is that they are the ones a great many programs
** have already run.
**
** They are '#include'd rather than compiled separately for the same
** reason 'onelua.c' includes the rest of the runtime: one translation
** unit is one set of compiler flags, and doc/Plan-2026-09.md 3.5 is
** emphatic that the flags are the difference between a libm that agrees
** across targets and one that does not.
**
** ------------------------------------------------------------- surface --
**
** Entry points:
**   diluvium_libm_install   the only thing outside this file calls
**
** Configurable values:
**   DVLIBM_ROUTED           the 'math' entries that are replaced, and
**                           the only place that list appears
**
** Fan-out points:
**   dvlibm_routed           the name-to-wrapper table
**   the '#include' block    the vendored sources, in dependency order
*/

